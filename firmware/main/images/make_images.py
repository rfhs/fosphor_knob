#!/usr/bin/env python3
"""Regenerate rfhs_logo.c from rfhs_logo.svg (run from anywhere, no arguments).

Needs rsvg-convert (librsvg) and Pillow (pip install pillow).

The logo always sits on the screen's black background, so it is drawn onto
black here and stored without alpha as RGB565. It is ordered-dithered the way
ui.c dithers the ring layer, so the logo's gradient doesn't band.
"""

import os
import subprocess
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SIZE = 176          # ui.c: its corners stay inside the glow ring

BAYER = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def pack565(r, g, b, t):
    return (((r * 31 + t) // 255) << 11) | (((g * 63 + t) // 255) << 5) | ((b * 31 + t) // 255)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "logo.png")
        subprocess.run(["rsvg-convert", "-b", "black", "-w", str(SIZE), "-h", str(SIZE),
                        os.path.join(HERE, "rfhs_logo.svg"), "-o", png], check=True)
        img = Image.open(png).convert("RGB")
    data = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = img.getpixel((x, y))
            data += pack565(r, g, b, BAYER[y & 3][x & 3] * 16 + 8).to_bytes(2, "little")

    rows = ["    " + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    with open(os.path.join(HERE, "rfhs_logo.c"), "w") as f:
        f.write("// Generated by make_images.py from rfhs_logo.svg; don't edit.\n\n")
        f.write('#include "lvgl.h"\n\n')
        f.write("static LV_ATTRIBUTE_LARGE_CONST const uint8_t rfhs_logo_map[] = {\n")
        f.write("\n".join(rows) + "\n};\n\n")
        f.write("const lv_image_dsc_t rfhs_logo = {\n")
        f.write("    .header = {\n")
        f.write("        .magic = LV_IMAGE_HEADER_MAGIC,\n")
        f.write("        .cf = LV_COLOR_FORMAT_RGB565,\n")
        f.write("        .w = %d,\n        .h = %d,\n        .stride = %d,\n" % (SIZE, SIZE, SIZE * 2))
        f.write("    },\n")
        f.write("    .data_size = sizeof(rfhs_logo_map),\n")
        f.write("    .data = rfhs_logo_map,\n")
        f.write("};\n")
    print("wrote rfhs_logo.c")


if __name__ == "__main__":
    main()
